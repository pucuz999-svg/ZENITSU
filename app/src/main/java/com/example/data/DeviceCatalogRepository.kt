    fun buildDetectedDeviceProfile(telemetry: SystemTelemetry): DeviceSensitivityProfile {
        val ramGb = (telemetry.totalRamMb / 1024f).roundToInt().coerceAtLeast(2)
        val hz = telemetry.maxSupportedRefreshRateHz
        val sw = telemetry.smallestWidthDp.coerceAtLeast(320)
        val isSamsung = telemetry.manufacturer.contains("samsung", ignoreCase = true)

        if (isSamsung) {
            val matchedSamsung = findBestSamsungMatch(telemetry.model)
            if (matchedSamsung != null) {
                return matchedSamsung.copy(
                    id = "detected_current_device",
                    brand = PlatformBrand.DETECTED,
                    deviceName = "${telemetry.manufacturer} ${telemetry.model}",
                    platformBadge = "One UI • Android ${telemetry.androidVersion} • ${telemetry.socLabel}",
                    ramTier = "${ramGb}GB RAM",
                    displayHz = hz.coerceAtLeast(matchedSamsung.displayHz.coerceAtMost(hz)),
                    screenSpec = "${telemetry.screenWidthPx}×${telemetry.screenHeightPx} • ${telemetry.densityDpi} DPI",
                    isDetectedCurrentDevice = true,
                )
            }
        }

        // Compute tailored 0-200 sensitivity based on actual device smallestWidthDp, RAM & Hz
        val isTablet = sw >= 600
        val scaleFactor = when {
            isTablet -> 0.86f
            sw >= 440 -> 0.94f
            sw <= 360 -> 1.04f
            else -> 1.0f
        }
        val hzFactor = if (hz >= 120) 1.03f else if (hz >= 90) 1.01f else 0.99f

        val general = (188 * scaleFactor * hzFactor).roundToInt().coerceIn(135, 200)
        val redDot = (182 * scaleFactor * hzFactor).roundToInt().coerceIn(130, 198)
        val scope2x = (168 * scaleFactor).roundToInt().coerceIn(120, 192)
        val scope4x = (152 * scaleFactor).roundToInt().coerceIn(105, 185)
        val sniper = (114 * scaleFactor).roundToInt().coerceIn(75, 165)
        val freeLook = (160 * scaleFactor).roundToInt().coerceIn(110, 190)
        val fireBtn = if (isTablet) 55 else if (sw >= 420) 48 else 51
        val recommendedDpi = if (isTablet) 720 else (sw + 110).coerceIn(420, 620)

        val fpsPreset = recommendFpsForHardware(ramGb, hz, telemetry.thermalLevel.name)

        return DeviceSensitivityProfile(
            id = "detected_current_device",
            brand = PlatformBrand.DETECTED,
            deviceName = "${telemetry.manufacturer} ${telemetry.model}",
            platformBadge = if (isSamsung) {
                "One UI • Android ${telemetry.androidVersion} • ${telemetry.socLabel}"
            } else {
                "Android ${telemetry.androidVersion} • ${telemetry.socLabel}"
            },
            ramTier = "${ramGb}GB RAM",
            displayHz = hz,
            screenSpec = "${telemetry.screenWidthPx}×${telemetry.screenHeightPx} • ${telemetry.densityDpi} DPI",
            baseSensitivity = SensitivityValues(
                general = general,
                redDot = redDot,
                scope2x = scope2x,
                scope4x = scope4x,
                sniperScope = sniper,
                freeLook = freeLook,
                fireButtonPercent = fireBtn,
                recommendedDpi = recommendedDpi,
            ),
            fpsPreset = fpsPreset,
            dragTip = when {
                isTablet -> "Large-screen tablet detected: use wider 55% Fire Button and moderate J-drag strokes for crisp head locks."
                isSamsung -> "Samsung One UI detected (${hz}Hz, ${sw}dp): enable Display Touch Sensitivity + Game Booster Performance mode for crisp drag headshots."
                else -> "Calibrated for ${telemetry.model} (${hz}Hz, ${sw}dp width): place Fire Button low-right and drag straight up."
            },
            preferredTouchSetting = if (isSamsung) {
                "One UI Touch Sensitivity: ON • Game Booster: Performance • Pointer Speed: Max • DPI: $recommendedDpi"
            } else {
                "Pointer Speed: High • Refresh Rate: ${hz}Hz • Recommended DPI: $recommendedDpi"
            },
            dragTechnique = if (isTablet) {
                "Wide-screen controlled J-drag with 55% Fire Button"
            } else {
                "Chest-lock straight upward snap (1.2cm swipe) at $fireBtn% Fire Button"
            },
            isDetectedCurrentDevice = true,
        )
    }

