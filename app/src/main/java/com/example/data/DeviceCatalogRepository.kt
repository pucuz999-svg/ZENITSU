    private fun recommendFpsForHardware(
        ramGb: Int,
        hz: Int,
        thermalName: String,
    ): FpsGraphicsPreset {
        return when {
            ramGb >= 8 && hz >= 120 -> FpsGraphicsPreset(
                graphicsQuality = if (thermalName == "HOT") "Standard" else "Ultra",
                fpsMode = "High",
                targetFps = 90,
                shadowEnabled = thermalName != "HOT",
                highResolution = "High",
                filter = "Vivid",
                autoScale = false,
                rationale = "${ramGb}GB RAM + ${hz}Hz panel easily sustains High FPS. Disable Shadow during long ranked marathons if temp exceeds 41°C.",
            )
            ramGb >= 6 && hz >= 90 -> FpsGraphicsPreset(
                graphicsQuality = "Standard",
                fpsMode = "High",
                targetFps = 90,
                shadowEnabled = false,
                highResolution = "High",
                filter = "Bright",
                autoScale = false,
                rationale = "Standard Graphics + High FPS locks frame pacing near ${hz}Hz while keeping SoC thermal throttling away.",
            )
            ramGb >= 4 -> FpsGraphicsPreset(
                graphicsQuality = "Smooth",
                fpsMode = "High",
                targetFps = 60,
                shadowEnabled = false,
                highResolution = "Normal",
                filter = "Classic",
                autoScale = true,
                rationale = "Smooth + High FPS prioritizes 60 FPS input responsiveness in crowded final zones on 4GB–6GB devices.",
            )
            else -> FpsGraphicsPreset(
                graphicsQuality = "Smooth",
                fpsMode = "Normal",
                targetFps = 45,
                shadowEnabled = false,
                highResolution = "Normal",
                filter = "Classic",
                autoScale = true,
                rationale = "Low-RAM stability preset prevents texture hitching and sudden crash-outs on entry-level hardware.",
            )
        }
    }

    fun getAllCuratedDevices(): List<DeviceSensitivityProfile> = curatedDevices

    fun suggestBestSmoothGameplay(
        telemetry: SystemTelemetry,
        priority: SmoothPlayPriority,
        targetDevice: DeviceSensitivityProfile,
    ): DeviceSmoothSuggestion {
        val baseFps = targetDevice.fpsPreset
        val isHot = targetDevice.isDetectedCurrentDevice && telemetry.thermalLevel == ThermalLevel.HOT
        val tunedFps = when (priority) {
            SmoothPlayPriority.MAX_FPS -> baseFps.copy(
                graphicsQuality = if (targetDevice.displayHz >= 120 && !isHot) "Standard" else "Smooth",
                fpsMode = "High",
                targetFps = targetDevice.displayHz.coerceAtMost(120),
                shadowEnabled = false,
                highResolution = if (targetDevice.displayHz >= 120) "High" else "Normal",
                filter = "Bright",
                autoScale = false,
                rationale = "Shadows OFF + High FPS unlocks maximum frame consistency (${targetDevice.displayHz.coerceAtMost(120)} FPS ceiling) on ${targetDevice.deviceName}.",
            )
            SmoothPlayPriority.ZERO_LAG_SQUAD -> baseFps.copy(
                graphicsQuality = "Smooth",
                fpsMode = "High",
                targetFps = if (targetDevice.displayHz >= 90) 90 else 60,
                shadowEnabled = false,
                highResolution = "Normal",
                filter = "Classic",
                autoScale = true,
                rationale = "Smooth + Auto-Scale eliminates particle & gloo-wall micro-stutter during 4v4 final circles.",
            )
            SmoothPlayPriority.BALANCED_HEADSHOT -> baseFps
        }

        val tunedSens = when (priority) {
            SmoothPlayPriority.MAX_FPS -> targetDevice.baseSensitivity.tunedFor(PlayStyleMode.ONE_TAP_DRAG)
            SmoothPlayPriority.ZERO_LAG_SQUAD -> targetDevice.baseSensitivity.tunedFor(PlayStyleMode.BALANCED_RUSH)
            SmoothPlayPriority.BALANCED_HEADSHOT -> targetDevice.baseSensitivity
        }

        val similar = curatedDevices
            .filter { it.id != targetDevice.id }
            .sortedBy { abs(it.displayHz - targetDevice.displayHz) }
            .take(3)

        val note = if (targetDevice.isDetectedCurrentDevice) {
            "Matched to your live ${telemetry.model} (${telemetry.totalRamMb / 1024}GB RAM, ${telemetry.maxSupportedRefreshRateHz}Hz, ${telemetry.thermalLevel.label} thermal)."
        } else {
            "Tailored for ${targetDevice.deviceName} (${targetDevice.ramTier}, ${targetDevice.displayHz}Hz panel)."
        }

        return DeviceSmoothSuggestion(
            targetDevice = targetDevice,
            priority = priority,
            recommendedFps = tunedFps,
            recommendedSensitivity = tunedSens,
            hardwareNote = note,
            similarDevices = similar,
        )
    }

